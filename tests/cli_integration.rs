use assert_cmd::Command;
use predicates::prelude::*;
use tempfile::TempDir;

struct TestSetup {
    config_dir: TempDir,
    home_dir: TempDir,
    work_dir: TempDir,
}

impl TestSetup {
    fn new() -> Self {
        TestSetup {
            config_dir: TempDir::new().unwrap(),
            home_dir: TempDir::new().unwrap(),
            work_dir: TempDir::new().unwrap(),
        }
    }

    fn write_project(&self, name: &str, content: &str) {
        std::fs::write(self.config_dir.path().join(format!("{name}.yml")), content).unwrap();
    }

    fn cmd(&self) -> Command {
        let mut cmd = Command::cargo_bin("bootmux").unwrap();
        cmd.env_clear()
            .env("PATH", std::env::var("PATH").unwrap())
            .env("HOME", self.home_dir.path())
            .env("TMUXINATOR_CONFIG", self.config_dir.path())
            .env("SHELL", "/bin/bash")
            .env("EDITOR", "true")
            .current_dir(self.work_dir.path());
        cmd
    }
}

const VALID_PROJECT: &str = "name: valid\nattach: false\nwindows:\n  - editor: vim\n";

#[test]
fn version_prints_bootmux_version() {
    let setup = TestSetup::new();
    setup
        .cmd()
        .arg("version")
        .assert()
        .success()
        .stdout(format!("bootmux {}\n", env!("CARGO_PKG_VERSION")));

    setup
        .cmd()
        .arg("-v")
        .assert()
        .success()
        .stdout(predicate::str::starts_with("bootmux "));
}

#[test]
fn commands_lists_all_command_names() {
    let setup = TestSetup::new();
    let assert = setup.cmd().arg("commands").assert().success();
    let output = String::from_utf8(assert.get_output().stdout.clone()).unwrap();
    for name in ["start", "stop", "stop_all", "debug", "implode", "version"] {
        assert!(output.lines().any(|line| line == name), "missing {name}");
    }

    setup
        .cmd()
        .args(["commands", "zsh"])
        .assert()
        .success()
        .stdout(predicate::str::contains(
            "debug:Output the shell commands that are generated by bootmux",
        ));
}

#[test]
fn completions_lists_projects_for_completable_commands() {
    let setup = TestSetup::new();
    setup.write_project("alpha", VALID_PROJECT);
    setup.write_project("beta", VALID_PROJECT);

    setup
        .cmd()
        .args(["completions", "start"])
        .assert()
        .success()
        .stdout("alpha\nbeta\n");

    setup
        .cmd()
        .args(["completions", "doctor"])
        .assert()
        .success()
        .stdout("");
}

#[test]
fn list_shows_projects() {
    let setup = TestSetup::new();
    setup.write_project("alpha", VALID_PROJECT);
    setup.write_project("beta", VALID_PROJECT);

    setup
        .cmd()
        .args(["list", "--newline"])
        .assert()
        .success()
        .stdout("bootmux projects:\nalpha\nbeta\n");
}

#[test]
fn debug_renders_project_script() {
    let setup = TestSetup::new();
    setup.write_project("demo", "name: demo\nwindows:\n  - editor: vim\n");

    setup
        .cmd()
        .args(["debug", "demo"])
        .assert()
        .success()
        .stdout(predicate::str::contains("new-session -d -s demo -n editor"))
        .stdout(predicate::str::contains("vim C-m"));
}

#[test]
fn debug_accepts_project_config_path_and_settings() {
    let setup = TestSetup::new();
    let config = setup.work_dir.path().join("templated.yml");
    std::fs::write(
        &config,
        "name: {{ settings.session | default('fallback') }}\nwindows:\n  - a: echo {{ args[0] }}\n",
    )
    .unwrap();

    setup
        .cmd()
        .args([
            "debug",
            "-p",
            config.to_str().unwrap(),
            "session=custom",
            "hello",
        ])
        .assert()
        .success()
        .stdout(predicate::str::contains("new-session -d -s custom"))
        .stdout(predicate::str::contains("echo\\ hello C-m"));
}

#[test]
