#[test]
fn missing_projects_report_ruby_compatible_errors() {
    let setup = TestSetup::new();

    setup
        .cmd()
        .args(["start", "nosuch"])
        .assert()
        .code(1)
        .stdout("Project nosuch doesn't exist.\n");

    setup
        .cmd()
        .args(["stop"])
        .assert()
        .code(1)
        .stdout("Project file at ./.tmuxinator.yml doesn't exist.\n");

    setup
        .cmd()
        .args(["debug", "-p", "missing.yml"])
        .assert()
        .code(1)
        .stdout("Project config (missing.yml) doesn't exist.\n");
}

#[test]
fn erb_configs_are_rejected_with_migration_hint() {
    let setup = TestSetup::new();
    setup.write_project(
        "legacy",
        "name: legacy\nwindows:\n  - a: echo <%= @args[0] %>\n",
    );

    setup
        .cmd()
        .args(["debug", "legacy"])
        .assert()
        .code(1)
        .stdout(predicate::str::contains("Failed to parse config file:"))
        .stdout(predicate::str::contains("MiniJinja"));
}

#[test]
fn new_generates_project_from_sample_and_opens_editor() {
    let setup = TestSetup::new();

    setup.cmd().args(["new", "fresh"]).assert().success();

    let created = setup.config_dir.path().join("fresh.yml");
    let content = std::fs::read_to_string(&created).unwrap();
    assert!(content.contains("name: fresh"));
    assert!(content.contains(created.to_str().unwrap()));
}

#[test]
fn copy_duplicates_project_files() {
    let setup = TestSetup::new();
    setup.write_project("origin", VALID_PROJECT);

    setup
        .cmd()
        .args(["copy", "origin", "clone"])
        .assert()
        .success();
    assert!(setup.config_dir.path().join("clone.yml").exists());

    setup
        .cmd()
        .args(["copy", "nosuch", "clone2"])
        .assert()
        .code(1)
        .stdout("Project nosuch doesn't exist!\n");
}

#[test]
fn delete_removes_project_after_confirmation() {
    let setup = TestSetup::new();
    setup.write_project("doomed", VALID_PROJECT);

    setup
        .cmd()
        .args(["delete", "doomed"])
        .write_stdin("y\n")
        .assert()
        .success()
        .stdout(predicate::str::contains("Deleted doomed"));
    assert!(!setup.config_dir.path().join("doomed.yml").exists());

    setup
        .cmd()
        .args(["delete", "ghost"])
        .assert()
        .success()
        .stdout(predicate::str::contains("ghost does not exist!"));
}

#[test]
fn implode_removes_config_directories() {
    let setup = TestSetup::new();
    setup.write_project("any", VALID_PROJECT);

    setup
        .cmd()
        .arg("implode")
        .write_stdin("y\n")
        .assert()
        .success()
        .stdout(predicate::str::contains("Deleted all bootmux projects."));
    assert!(!setup.config_dir.path().exists());
}

#[test]
fn doctor_reports_environment_checks() {
    let setup = TestSetup::new();
    let assert = setup.cmd().arg("doctor").assert().success();
    let output = String::from_utf8(assert.get_output().stdout.clone()).unwrap();
    assert!(output.contains("Checking if tmux is installed ==> "));
    assert!(output.contains("Checking if $EDITOR is set ==> "));
    assert!(output.contains("Checking if $SHELL is set ==> "));
}

#[test]
fn projects_in_subdirectories_are_found_by_basename() {
    let setup = TestSetup::new();
    let sub = setup.config_dir.path().join("team");
    std::fs::create_dir_all(&sub).unwrap();
    std::fs::write(sub.join("nested.yml"), "name: nested\nwindows: []\n").unwrap();

    setup
        .cmd()
        .args(["debug", "nested"])
        .assert()
        .code(1)
        .stdout("Your project file should include some windows.\n");

    setup
        .cmd()
        .args(["list", "-n"])
        .assert()
        .success()
        .stdout("bootmux projects:\nteam/nested\n");
}
